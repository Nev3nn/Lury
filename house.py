def _shape(c, s, x, y):
    if s[0] == "p":
        c.create_polygon([v + (x if i % 2 == 0 else y) for i, v in enumerate(s[1])], fill=s[2], outline="")
    else:
        (c.create_rectangle if s[0] == "r" else c.create_oval)(x + s[1], y + s[2], x + s[3], y + s[4], fill=s[5], outline="")

def _base(c):
    c.create_rectangle(0, 0, 680, 430, fill="#151a2b", outline="")
    for x, y in [(40, 30), (120, 60), (300, 25), (520, 20), (650, 90), (200, 90)]:
        c.create_oval(x, y, x + 3, y + 3, fill="#f5f0d0", outline="")
    c.create_oval(610, 25, 645, 60, fill="#f3e9b5", outline="")
    c.create_rectangle(0, 370, 680, 430, fill="#2b5a3c", outline="")
    c.create_polygon(80, 152, 340, 50, 600, 152, fill="#8a3b3b", outline="#5e2626", width=2)
    c.create_rectangle(470, 70, 500, 125, fill="#7a3030", outline="")
    c.create_rectangle(100, 150, 580, 370, fill="#d9c7a6", outline="#5b4630", width=3)
    for i, (name, col) in enumerate(ROOMS):
        x0, y0 = 100 + 160 * (i % 3), 152 if i < 3 else 262
        c.create_rectangle(x0 + 2, y0, x0 + 158, y0 + 104, fill=col, outline="#8a7a62")
        c.create_rectangle(x0 + 2, y0 + 100, x0 + 158, y0 + 104, fill="#8a6a45", outline="")
        c.create_rectangle(x0 + 112, y0 + 12, x0 + 148, y0 + 50, fill="#27405e", outline="#5b4630", width=2)
        c.create_line(x0 + 130, y0 + 12, x0 + 130, y0 + 50, fill="#cfd8dc")
        c.create_line(x0 + 112, y0 + 31, x0 + 148, y0 + 31, fill="#cfd8dc")
        c.create_text(x0 + 8, y0 + 5, text=name, anchor="nw", fill="#5b4630", font=("Segoe UI", 8, "bold"))
    c.create_rectangle(100, 256, 580, 262, fill="#4a3a2a", outline="")

def draw(c, owned):
    c.delete("all"); _base(c)
    for name, _e, _p, x, y, ext, shapes in ITEMS:
        if name in owned:
            for s in shapes: _shape(c, s, x + (0 if ext else OX), y)
    c.scale("all", 0, 0, K, K)
